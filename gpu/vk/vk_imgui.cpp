bool begin(uint32_t w, uint32_t h) {
    if (!tried) ready = init();
    if (!ready || (!dev.offscreen && dev.swap_views.empty())) return false;
    if (target_format() != pipeline_format) {   // (a new swapchain of another format: create_swapchain waited for the device)
        pipeline_format = target_format();
        srgb_target = is_srgb(pipeline_format);
        ImGui_ImplVulkan_PipelineInfo pi{};
        pi.PipelineRenderingCreateInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO;
        pi.PipelineRenderingCreateInfo.colorAttachmentCount = 1;
        pi.PipelineRenderingCreateInfo.pColorAttachmentFormats = &pipeline_format;
        ImGui_ImplVulkan_CreateMainPipeline(&pi);
        logf("vk: ui: the window's images are now format %d%s", (int)pipeline_format, srgb_target ? " (sRGB)" : "");
    }
    ImGuiIO& io = ImGui::GetIO();
    io.DisplaySize = ImVec2((float)w, (float)h);
    static int64_t last = 0;
    const int64_t now = prof_now();
    io.DeltaTime = last && now > last ? std::min((float)((now - last) / 1e9), 0.25f) : 1.0f / 60.0f;
    last = now;
    ImGui_ImplVulkan_NewFrame();
    ImGui::NewFrame();
    bake_some();
    return true;
}
const Fonts& fonts() { return fonts_; }
void prebake(const float* px, int n) {
    if (!ready) return;
    to_bake.clear(), kept.clear(), baked_sizes.clear();   // (the sizes of the unit now only)
    for (int i = 0; i < n; i++) {
        const float size = std::round(px[i] * 100.0f) / 100.0f;
        if (std::find(baked_sizes.begin(), baked_sizes.end(), size) != baked_sizes.end()) continue;
        baked_sizes.push_back(size);
        for (ImFont* f : {fonts_.body, fonts_.strong, fonts_.heading}) to_bake.push_back({f, px[i]}), kept.push_back({f, px[i]});
    }
}
