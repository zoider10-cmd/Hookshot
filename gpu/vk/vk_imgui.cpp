std::vector<ImTextureData*> pictures_dying;   // (a picture's old size: let go once the backend destroyed it)
ImTextureData* picture(ImTextureData*& slot, int w, int h, const void* rgba) {
    for (size_t i = 0; i < pictures_dying.size();) {
        ImTextureData* t = pictures_dying[i];
        if (t->Status == ImTextureStatus_Destroyed) {
            ImGui::UnregisterUserTexture(t);
            IM_DELETE(t);
            pictures_dying.erase(pictures_dying.begin() + (ptrdiff_t)i);
        } else i++;
    }
    if (slot && (slot->Width != w || slot->Height != h)) {
        if (slot->Status == ImTextureStatus_WantCreate) {   // (never made: nothing to destroy)
            ImGui::UnregisterUserTexture(slot);
            IM_DELETE(slot);
        } else {
            slot->SetStatus(ImTextureStatus_WantDestroy);
            pictures_dying.push_back(slot);
        }
        slot = nullptr;
    }
    if (!slot) {
        slot = IM_NEW(ImTextureData)();
        slot->Create(ImTextureFormat_RGBA32, w, h);
        memcpy(slot->GetPixels(), rgba, (size_t)w * h * 4);
        slot->UseColors = true;
        ImGui::RegisterUserTexture(slot);
        return slot;
    }
    memcpy(slot->GetPixels(), rgba, (size_t)w * h * 4);
    if (slot->Status != ImTextureStatus_WantCreate) {
        const ImTextureRect all{0, 0, (unsigned short)w, (unsigned short)h};
        slot->Updates.clear();
        slot->Updates.push_back(all);
        slot->UpdateRect = all;
        slot->SetStatus(ImTextureStatus_WantUpdates);
    }
    return slot;
}

void idle() {
    if (!ready) return;
    presents++;
    reap(false);   // (staging buffers and old textures let go while nothing shows too)
}

void record_to(VkCommandBuffer cmd, VkImage image, VkImageView view, uint32_t w, uint32_t h) {
    ImGui::Render();
    ImDrawData* dd = ImGui::GetDrawData();
    presents++;
    reap(false);
    if (srgb_target) linearize(dd);
    else if (dev.hdr) hdr10(dd);   // (the overlays at the paper white, not at the display's peak with the wrong primaries)
    if (!image || !view) return;
    bool textures_ok = true;   // (a texture that could not be made has no descriptor: draws that sample it must not be recorded)
    if (dd->Textures)
        for (ImTextureData* tex : *dd->Textures) {
            if (tex->Status == ImTextureStatus_OK || tex->Status == ImTextureStatus_Destroyed) continue;
            update_texture(cmd, tex);
            if (tex->Status != ImTextureStatus_OK && tex->Status != ImTextureStatus_Destroyed) textures_ok = false;
        }
    dd->Textures = nullptr;   // (done above: the backend's own upload would wait on the queue)
    if (!textures_ok) {   // (this frame's overlays left out; the texture is asked for again next frame)
        static bool told = false;
        if (!told) told = true, logf("vk: ui: a texture could not be made (out of memory?): the overlays wait for it");
        return;
    }
    layout(cmd, image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_PIPELINE_STAGE_2_ALL_TRANSFER_BIT,
           VK_ACCESS_2_TRANSFER_WRITE_BIT, VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT,
           VK_ACCESS_2_COLOR_ATTACHMENT_READ_BIT | VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT);
    VkRenderingAttachmentInfo ca{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
    ca.imageView = view;
    ca.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    ca.loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    ca.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO};
    ri.renderArea = {{0, 0}, {w, h}};
    ri.layerCount = 1;
    ri.colorAttachmentCount = 1;
    ri.pColorAttachments = &ca;
    vkCmdBeginRendering(cmd, &ri);
    ImGui_ImplVulkan_RenderDrawData(dd, cmd);
    vkCmdEndRendering(cmd);
    layout(cmd, image, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
           VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT, VK_PIPELINE_STAGE_2_ALL_TRANSFER_BIT,
           VK_ACCESS_2_TRANSFER_READ_BIT | VK_ACCESS_2_TRANSFER_WRITE_BIT);
}

void record(VkCommandBuffer cmd, uint32_t index, uint32_t w, uint32_t h) {
    const bool has = index < dev.swap_views.size() && dev.swap_views[index];
    record_to(cmd, has ? dev.swap_images[index] : VK_NULL_HANDLE, has ? dev.swap_views[index] : VK_NULL_HANDLE, w, h);
}

