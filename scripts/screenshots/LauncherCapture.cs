// Render the launcher's maintained views with synthetic state, without a desktop,
// game files, build/download commands, input events or an executed save transfer.
using Avalonia;
using Avalonia.Headless;
using Avalonia.Threading;
using HookshotLauncher;
using HookshotLauncher.Core;
using HookshotLauncher.ViewModels;
using System.Security.Cryptography;

static class LauncherCapture
{
    [STAThread]
    static void Main(string[] args)
    {
        if (args.Length != 2) throw new ArgumentException("Expected an empty state directory and output directory.");
        string state = Path.GetFullPath(args[0]), output = Path.GetFullPath(args[1]);
        if (!Directory.Exists(state) || Directory.EnumerateFileSystemEntries(state).Any())
            throw new InvalidOperationException("State directory must be the empty directory reserved by the capture helper.");
        Directory.CreateDirectory(output);
        Environment.SetEnvironmentVariable("HOOKSHOT_LAUNCHER_OFFLINE", "1");
        Environment.SetEnvironmentVariable("HOOKSHOT_LAUNCHER_REDUCED_MOTION", "1");
        Environment.SetEnvironmentVariable("HOOKSHOT_LAUNCHER_HOME", Path.Combine(state, "launcher"));
        AppBuilder.Configure<App>().UseSkia()
            .UseHeadless(new AvaloniaHeadlessPlatformOptions { UseHeadlessDrawing = false })
            .SetupWithoutStarting();

        var service = LauncherService.Open(Platform.Linux, new LauncherHome(Path.Combine(state, "launcher")));
        service.SaveEnv = new SaveEnvironment(Platform.Linux, key => key switch
        {
            "XDG_DATA_HOME" => Path.Combine(state, "data"),
            _ => state,
        });
        service.Gpus = Array.Empty<string>();
        service.Settings.BuildsFolder = Path.Combine(state, "builds");
        service.Settings.DefaultChannel = Versions.Candidate; // Explicit illustrative build selection, independent of Launcher channel.
        service.Settings.HookshotSavesAsked = true;
        service.SetNewest(Versions.Candidate, "v3.0.0-rc.3");
        service.Checked = true;
        var main = new MainViewModel(service, StartRequest.Parse(Array.Empty<string>()));
        Capture(main, output, "launcher-home.png");
        string build = Path.Combine(state, "builds", "example-build");
        Directory.CreateDirectory(Path.Combine(build, "bin"));
        File.WriteAllText(Path.Combine(build, "bin", "hookshot"), "SYNTHETIC UI MARKER: not executable, not a game.");
        File.WriteAllText(Path.Combine(build, "hookshot_version.txt"), "version=v3.0.0-rc.3\n");
        service.Registry.Add(build, "v3.0.0-rc.3", Versions.Candidate, makeDefault: true);
        main = new MainViewModel(service, StartRequest.Parse(Array.Empty<string>()));
        Capture(main, output, "launcher-manage-saves.png");

        var emptySaves = new SavesViewModel(main);
        main.Navigate(emptySaves);
        Capture(main, output, "launcher-saves.png");
        main.Modal = new SavePickViewModel(emptySaves, SaveMode.Import) { Pick = "folder" };
        Capture(main, output, "launcher-import.png");
        main.Modal = null;

        // The capture helper replaces only StartSearch in the temporary build, so
        // this constructor cannot discover private game filenames on mounted drives.
        var job = new BuildJob(main, JobKind.Build, Versions.Candidate, "v3.0.0-rc.3", null);
        var files = new FilesStepViewModel(job, tools: false);
        files.ShowToolsAt(1, 0); // Maintained screenshot API; no actual download.
        job.ToolsDownloaded = false; // Show the maintained "Already on this PC" state.
        main.Navigate(files);
        Capture(main, output, "launcher-game-files.png");
        job.Stop();

        // Text-only fixture files follow the launcher's existing save-test convention.
        // No game-generated bytes, player names, account identifiers or real paths.
        string from = Path.Combine(state, "example-import"), to = Saves.ImportTarget(service.SaveEnv);
        foreach (string folder in new[] { from, to })
        {
            Directory.CreateDirectory(Path.Combine(folder, "slot_00"));
            File.WriteAllText(Path.Combine(folder, "account.sav"), "SYNTHETIC UI FIXTURE ONLY");
            File.WriteAllText(Path.Combine(folder, "option.sav"), "SYNTHETIC UI FIXTURE ONLY");
            File.WriteAllText(Path.Combine(folder, "slot_00", "caption.sav"), "SYNTHETIC UI FIXTURE ONLY");
        }
        var before = Fingerprints(state);
        var saves = new SavesViewModel(main);
        var confirm = new SavesConfirmViewModel(saves, new SaveOp { Mode = SaveMode.Import, Folder = from });
        if (confirm.Problem != null || confirm.FromEmpty || confirm.ToEmpty)
            throw new InvalidOperationException("Synthetic confirmation state is incomplete: " + confirm.Problem);
        main.Navigate(confirm);
        Capture(main, output, "launcher-import-confirm.png");
        // The real constructor computes a dry-run backup preview. Nothing may copy,
        // create a backup, modify a fixture, or invoke the Import command.
        if (!before.SequenceEqual(Fingerprints(state))) throw new InvalidOperationException("Capture changed fixture files.");
        Console.WriteLine("Rendered six maintained Launcher views; no build or transfer executed.");
    }

    static string[] Fingerprints(string root) => Directory.GetFiles(root, "*", SearchOption.AllDirectories)
        .Select(p => "F:" + p + ":" + Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(p))))
        .Concat(Directory.GetDirectories(root, "*", SearchOption.AllDirectories).Select(p => "D:" + p))
        .OrderBy(p => p, StringComparer.Ordinal).ToArray();

    static void Capture(MainViewModel main, string output, string filename)
    {
        var window = new MainWindow { Width = 960, Height = 600, DataContext = main };
        window.Show();
        // Settle layout and the asynchronous illustrative requirements result.
        for (int i = 0; i < 30; ++i) { Dispatcher.UIThread.RunJobs(); Thread.Sleep(50); }
        using var frame = window.CaptureRenderedFrame() ?? throw new InvalidOperationException("No rendered frame.");
        frame.Save(Path.Combine(output, filename), Avalonia.Media.Imaging.PngBitmapEncoderOptions.Default);
        window.Close();
        Dispatcher.UIThread.RunJobs();
    }
}
