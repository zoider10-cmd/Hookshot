"""TBL with a one-register table and EXT (nx2/fastvec.py's vectorize_bytes: a64_tbl1, A64_EXT16, A64_EXT8), bit-exact with
the byte loops the emitter writes for them, game-free.

Guest words (TBL 8 and 16 bytes; EXT 16 bytes at every imm 0-15 and 8 bytes at every imm 0-7; Vd apart, Vd = Vn, Vd = Vm,
one register for all, registers above 15) go through a64emit.translate and a64_lift.op_text twice: as lifted now and with
A64_NO_VBYTES=1 (as before). The first must call the helper and keep no byte loop, the second must be the loop.
tests/vbytes_test.c runs both from the same random Ctx (index bytes biased to the edges: 15, 16, 0x6f-0x90, 0xff) and
compares all 32 vector registers. Built for -march=native, x86-64-v3, x86-64-v2 (SSSE3: the PSHUFB path) and x86-64
(SSE2 only: the fallback), on Windows and Linux; a build this CPU cannot run (x86-64-v3 without AVX2, say) exits 3 at
once and is reported as skipped. Then timed at the game's -O1 -march=native.

    python -I -B tests/test_vbytes.py [--cc clang] [--cxx clang++] [--random 1000000]
"""
import argparse
import os
import platform
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tests"))
import test_fpx_sticky as fs  # noqa: E402

SEED = 20261115
MARCHES = ("native", "x86-64-v3", "x86-64-v2", "x86-64")
REGS = ((0, 5, 1), (5, 5, 1), (1, 5, 1), (2, 2, 2), (3, 30, 17))   # (rd, rn, rm)


def tbl(q, rd, rn, rm):
    return 0x0E000000 | (q << 30) | (rm << 16) | (rn << 5) | rd


def ext(q, rd, rn, rm, imm):
    return 0x2E000000 | (q << 30) | (rm << 16) | (imm << 11) | (rn << 5) | rd


def shapes():
    out = []
    for q in (0, 1):
        for r in REGS:
            out.append(("TBL v%d.%s, {v%d.16b}, v%d.%s" % (r[0], "16b" if q else "8b", r[1], r[2], "16b" if q else "8b"),
                        tbl(q, *r), "a64_tbl1("))
    for q, n in ((1, 16), (0, 8)):
        for imm in range(n):
            for r in (REGS if imm in (0, 1, n // 2, n - 1) else REGS[:1]):
                out.append(("EXT v%d.%s, v%d, v%d, #%d" % (r[0], "16b" if q else "8b", r[1], r[2], imm),
                            ext(q, *r, imm), "A64_EXT%d(" % n))
    return out


def ldr_q(rt, rn, imm16):
    return 0x3DC00000 | ((imm16 // 16) << 10) | (rn << 5) | rt


def ldp_q(rt, rt2, rn, imm16):
    return 0xAD400000 | (((imm16 // 16) & 0x7f) << 15) | (rt2 << 10) | (rn << 5) | rt


def ld1_16b(rt, rn):
    return 0x4C407000 | (rn << 5) | rt


def ldr_q_post(rt, rn, imm9):
    return 0x3CC00400 | ((imm9 & 0x1ff) << 12) | (rn << 5) | rt


def dup_elem(q, size, idx, rd, rn):
    imm5 = (idx << (size + 1)) | (1 << size)
    return 0x0E000400 | (q << 30) | (imm5 << 16) | (rn << 5) | rd


def move_shapes():
    out = [("LDR q3, [x1, #32]", ldr_q(3, 1, 32), "a64_vld16("), ("LDR q31, [x7]", ldr_q(31, 7, 0), "a64_vld16("),
           ("LDP q2, q9, [x1, #-64]", ldp_q(2, 9, 1, -64), "a64_vld16("),
           ("LDR q5, [x3], #48", ldr_q_post(5, 3, 48), "a64_vld16(")]
    for size, lanes in ((0, 16), (1, 8), (2, 4), (3, 2)):
        for q in ((1,) if size == 3 else (0, 1)):
            for idx in sorted({0, 1, lanes - 1}):
                for rd, rn in ((6, 2), (2, 2), (17, 30)):
                    out.append(("DUP v%d.%d%s, v%d[%d]" % (rd, (lanes if q else lanes // 2), "bhsd"[size], rn, idx),
                                dup_elem(q, size, idx, rd, rn), "a64_vdup("))
    return out


def lifted_cases(a64emit, a64_lift, used):
    cases = shapes() + move_shapes()
    texts, fl = a64emit.translate([(0x1000 + 4 * i, w) for i, (_, w, _) in enumerate(cases)])
    if any(fl):
        raise SystemExit("vbytes: a64emit did not translate the guest words: %s" % fl)
    now = [a64_lift.op_text(t, used) for t in texts]
    os.environ["A64_NO_VBYTES"] = os.environ["A64_NO_VMOVES"] = "1"
    try:
        old = [a64_lift.op_text(t, used) for t in texts]
    finally:
        del os.environ["A64_NO_VBYTES"], os.environ["A64_NO_VMOVES"]
    out = ["/* Generated by tests/test_vbytes.py: TBL (one register) and EXT, as lifted now and as before. */"]
    for i, (n, o, (name, _, helper)) in enumerate(zip(now, old, cases)):
        if helper not in n or "for(int _i" in n:
            raise SystemExit("vbytes: %s was not rewritten: %s" % (name, n[:300]))
        if helper in o:
            raise SystemExit("vbytes: %s as before already has the helper: %s" % (name, o[:300]))
        out.append("static void g_now%d(Ctx *__restrict c) { %s }" % (i, n))
        out.append("static void g_old%d(Ctx *__restrict c) { %s }" % (i, o))
    out.append("static const struct { const char *name; void (*now)(Ctx *), (*old)(Ctx *); } CASES[] = {%s};"
               % ", ".join('{"%s", g_now%d, g_old%d}' % (c[0], i, i) for i, c in enumerate(cases)))
    return "\n".join(out) + "\n"


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    fs.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(fs.KIT, "lift", "a64emit.cpp")]
             + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    import suyu_rt_fixes
    suyu_rt_fixes.install()
    import fastvec   # (the passes under test live there, around the kit's: nx2/fastvec.py)
    fastvec.install()
    used = set()
    try:
        a64_rtgen.write(tmp)
        lifted = lifted_cases(a64emit, a64_lift, used)
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    with open(os.path.join(tmp, "vbytes_lifted.h"), "w", newline="\n") as f:
        f.write(lifted)
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        f.write(a64_lift.fpx_header(used))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    p.add_argument("--random", type=int, default=1000000)
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        fs.skip("not an x86-64 host: %s" % platform.machine())
    cc = fs.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
    cxx = fs.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    if not cc or not cxx:
        fs.skip("no C compiler" if not cc else "no C++ compiler")
    t0 = time.time()
    failed = []
    with tempfile.TemporaryDirectory(prefix="longshot-vbytes-") as tmp:
        generate(cxx, tmp, fs.target_flags(cxx, tmp))
        for march in MARCHES:
            exe = os.path.join(tmp, "vbytes_test_%s.exe" % march)
            fs.build([cc] + fs.target_flags(cc, tmp) + ["-march=" + march] + fs.FLAGS +
                     ["-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp,
                      os.path.join(ROOT, "tests", "vbytes_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe],
                     "the driver at " + march)
            r = fs.run([exe, "random", str(a.random), str(SEED)], timeout=1800)
            print("%-10s %s" % (march, r.stdout.rstrip()))
            if r.returncode == 3:   # (tests/x86_test_host.h: this CPU lacks an extension of that -march)
                print("%-10s skipped (this CPU is not %s)" % (march, march))
                continue
            if r.returncode:
                failed.append("%s (exit %d)" % (march, r.returncode))
        exe = os.path.join(tmp, "vbytes_time.exe")
        fs.build([cc] + fs.target_flags(cc, tmp) + ["-march=native", "-ffp-contract=off", "-fno-strict-aliasing", "-O1",
                  "-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp,
                  os.path.join(ROOT, "tests", "vbytes_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the timing driver")
        r = fs.run([exe, "time"], timeout=1800)
        print("timing at -O1 -march=native:\n" + r.stdout.rstrip())
    print("vbytes: %s in %.0f s" % ("FAILED: " + ", ".join(failed) if failed else "ok", time.time() - t0))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
