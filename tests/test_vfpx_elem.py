"""FMUL Vd.4S, Vn.4S, Vm.S[i] (FMUL by element, four lanes) lifted to a64_vfpx_mul32 over a broadcast of the element
(nx2/fastvec.py's VFPX_MUL_ELEM), bit-exact with the four scalar a64_fpx_mul32_fma32 calls it replaces, game-free.

Guest words of the form (several registers, every lane index, Vd the same as Vn or as Vm, an Rm above 15) go through
a64emit.translate and a64_lift.op_text, the lifter's per-instruction pipeline, twice: as lifted now, and with
A64_NO_VFPX_ELEM=1 (as before the change). The first must call a64_vfpx_mul32 and no scalar helper, the second the
scalar helper four times. tests/vfpx_elem_test.c then runs both from the same random Ctx and compares the whole Ctx:
  - random: 2M states per guest word (fpx_sticky_test.c's operand classes, products at the underflow and overflow
    edges, random FPCR with FZ, DN, RMode, FIZ/AH/NEP and the kill switch, random FPSR);
  - sweep: every pair of 54 special values (zeros, subnormals, the smallest and largest normals, inf, quiet and
    signalling NaNs, products exactly at the edges) as a lane and as the element, FZ on and off, four FPSR states.
Built like tests/test_fpx_sticky.py (a64emit from its source, a64_fpx.h by a64_lift.fpx_header, a64_suyu.c by
a64_rtgen) at the lifted code's FP flags, for -march=native (what the game is built for on this PC), x86-64-v3 and
x86-64-v2, on Windows and Linux; a build this CPU cannot run (x86-64-v3 without AVX2, say) exits 3 at once and is
reported as skipped.

    python -I -B tests/test_vfpx_elem.py [--cc clang] [--cxx clang++] [--random 2000000]
"""
import argparse
import os
import platform
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tests"))
import test_fpx_sticky as fs  # noqa: E402  (its compiler, target, build and run helpers; its paths on sys.path)

SEED = 20261115
MARCHES = ("native", "x86-64-v3", "x86-64-v2")
# (rd, rn, rm, index): Vd apart, Vd = Vn, Vd = Vm, the last lane, one register for all three, Rm above 15 (the M bit)
SHAPES = ((0, 5, 1, 0), (5, 5, 1, 0), (1, 5, 1, 2), (0, 5, 1, 3), (2, 2, 2, 1), (3, 7, 17, 2))


def word(rd, rn, rm, index):
    """FMUL Vd.4S, Vn.4S, Vm.S[index]: Q=1, sz=0, L = index bit 0, H = index bit 1, M = Rm bit 4, opcode 1001"""
    return 0x4F809000 | ((index & 1) << 21) | ((rm >> 4) << 20) | ((rm & 15) << 16) | ((index >> 1) << 11) | (rn << 5) | rd


def lifted_cases(a64emit, a64_lift, used):
    words = [(0x1000 + 4 * i, word(*s)) for i, s in enumerate(SHAPES)]
    texts, fl = a64emit.translate(words)
    if any(fl):
        raise SystemExit("vfpx elem: a64emit did not translate the guest words: %s" % fl)
    now = [a64_lift.op_text(t, used) for t in texts]
    os.environ["A64_NO_VFPX_ELEM"] = "1"
    try:
        old = [a64_lift.op_text(t, used) for t in texts]
    finally:
        del os.environ["A64_NO_VFPX_ELEM"]
    out = ["/* Generated by tests/test_vfpx_elem.py: FMUL by element, as nx2/fastvec.py lifts it now and as before. */"]
    for i, (n, o, s) in enumerate(zip(now, old, SHAPES)):
        if "a64_vfpx_mul32_elem(" not in n or "a64_fpx_mul32_fma32(" in n:
            raise SystemExit("vfpx elem: shape %s was not rewritten: %s" % (s, n[:300]))
        if o.count("a64_fpx_mul32_fma32(") != 1 or "a64_vfpx_mul32(" in o:   # (one call in a four-lane loop)
            raise SystemExit("vfpx elem: shape %s as before is not the scalar loop: %s" % (s, o[:300]))
        out.append("static void g_now%d(Ctx *__restrict c) { %s }" % (i, n))
        out.append("static void g_old%d(Ctx *__restrict c) { %s }" % (i, o))
    out.append("static const struct { const char *name; int rd, rn, rm, index; void (*now)(Ctx *), (*old)(Ctx *); } CASES[] = {%s};"
               % ", ".join('{"FMUL v%d.4s, v%d.4s, v%d.s[%d]", %d, %d, %d, %d, g_now%d, g_old%d}' % (s + s + (i, i))
                           for i, s in enumerate(SHAPES)))
    return "\n".join(out) + "\n"


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    fs.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(fs.KIT, "lift", "a64emit.cpp")]
             + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    import suyu_rt_fixes
    suyu_rt_fixes.install()
    import fastvec   # (the passes under test live there, around the kit's: nx2/fastvec.py)
    fastvec.install()
    used = set()
    try:
        a64_rtgen.write(tmp)
        lifted = lifted_cases(a64emit, a64_lift, used)
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    with open(os.path.join(tmp, "vfpx_elem_lifted.h"), "w", newline="\n") as f:
        f.write(lifted)
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        f.write(a64_lift.fpx_header(used | {("mul32", "fma32", 2, 3)}))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    p.add_argument("--random", type=int, default=2000000)
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        fs.skip("not an x86-64 host: %s" % platform.machine())
    cc = fs.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
    cxx = fs.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    if not cc or not cxx:
        fs.skip("no C compiler" if not cc else "no C++ compiler")
    t0 = time.time()
    failed = []
    with tempfile.TemporaryDirectory(prefix="longshot-vfpx-elem-") as tmp:
        generate(cxx, tmp, fs.target_flags(cxx, tmp))
        for march in MARCHES:
            exe = os.path.join(tmp, "vfpx_elem_test_%s.exe" % march)
            fs.build([cc] + fs.target_flags(cc, tmp) + ["-march=" + march] + fs.FLAGS +
                     ["-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp,
                      os.path.join(ROOT, "tests", "vfpx_elem_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe],
                     "the driver at " + march)
            for args in (["random", str(a.random), str(SEED)], ["sweep"]):
                r = fs.run([exe] + args, timeout=1800)   # (time: below normal priority, as every run here; best of 5)
                print("%-10s %s" % (march, r.stdout.rstrip()))
                if r.returncode == 3:   # (tests/x86_test_host.h: this CPU lacks an extension of that -march)
                    print("%-10s skipped (this CPU is not %s)" % (march, march))
                    break
                if r.returncode:
                    failed.append("%s %s (exit %d)" % (march, args[0], r.returncode))
        # (how long each takes, at what the game's lifted files are built with: -O1 for this CPU; nx2/build.py)
        exe = os.path.join(tmp, "vfpx_elem_time.exe")
        fs.build([cc] + fs.target_flags(cc, tmp) + ["-march=native", "-ffp-contract=off", "-fno-strict-aliasing", "-O1",
                  "-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp,
                  os.path.join(ROOT, "tests", "vfpx_elem_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the timing driver")
        r = fs.run([exe, "time"], timeout=1800)
        print("timing at -O1 -march=native:\n" + r.stdout.rstrip())
    if failed:
        raise SystemExit("vfpx elem: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("vfpx elem: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
