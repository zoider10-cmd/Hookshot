"""shipped_embed.py <merged list> [<header>]: (Mako 3.6.1) the merged pipeline state list (nx2/pipeline_states.py merge) as
gpu/vk/vk_shipped_list.h, zstd-compressed, built into hookshot_vk.dll. The in-game update only downloads the dll, so a dll update
brings the lists with it: gpu/vk/vk_draw.cpp (shipped_list_install) writes it as the game folder's
hookshot_pipeline_states_shipped.bin when that one is missing or smaller. Hashes, formats and draw state only: no game code or data
(assets/pipeline_states/README.md)."""
import os, struct, sys

import zstandard


def main(argv):
    src = argv[0]
    out = argv[1] if len(argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "gpu", "vk", "vk_shipped_list.h")
    data = open(src, "rb").read()
    if data[:8] != b"HKSTATE2":
        sys.exit("not a version 2 state list")
    rec = struct.unpack_from("<I", data, 8)[0]
    count = (len(data) - 12) // rec
    packed = zstandard.ZstdCompressor(level=19, write_content_size=True).compress(data)
    lines = [
        "// Generated by nx2/shipped_embed.py from the merged pipeline state list (assets/pipeline_states/): do not edit.",
        "// Hashes, formats and draw state only: no game code or data. gpu/vk/vk_draw.cpp: shipped_list_install",
        "#pragma once",
        f"static const unsigned long long kShippedListSize = {len(data)}ull;   // (uncompressed)",
        f"static const unsigned kShippedListPipelines = {count}u;",
        f"alignas(8) static const unsigned char kShippedListZst[{len(packed)}] = {{",
    ]
    for i in range(0, len(packed), 32):
        lines.append(",".join(str(b) for b in packed[i:i + 32]) + ",")
    lines.append("};")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {count} pipelines, {len(data)} bytes, {len(packed)} compressed")


if __name__ == "__main__":
    main(sys.argv[1:])
